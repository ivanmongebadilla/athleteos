def translate_descriptors(text):
    result = []
    pattern = re.compile(r'[a-z]+(?:-[a-z]+)*|\d+(?:/\d+)?|[^a-z\d\s]', re.I)
    text = text.strip(' ()-,')
    while text:
        found = False
        for key in sorted(modifiers, key=len, reverse=True):
            if text.startswith(key) and (len(text) == len(key) or not text[len(key)].isalpha()):
                result.append(modifiers[key]); text = text[len(key):].lstrip(' ()-,'); found = True; break
        if found: continue
        match = pattern.match(text)
        if not match: break
        token = match.group()
        if token.isalpha(): unknown.add(token)
        result.append(token); text = text[len(token):].lstrip(' ()-,')
    return ', '.join(result).replace(', .', '.').replace(', °', '°')
def translate(name):
    if name in overrides: return overrides[name]
    text = name.lower().replace('в°', '°').replace('_', ' ').replace('biceps curls', 'biceps curl')
    equipment = ''
    for key in sorted(equipment_prefix, key=len, reverse=True):
        if text.startswith(key+' '): equipment=equipment_prefix[key]; text=text[len(key)+1:]; break
    main = None
    for key in sorted(movements, key=len, reverse=True):
        match = re.search(r'(?<![a-z])'+re.escape(key)+r'(?![a-z])', text)
        if match:
            main = movements[key]; text=text[:match.start()]+' '+text[match.end():]; break
    desc = translate_descriptors(text)
    label = (main + (f' ({desc})' if desc else '') if main else desc) + (' '+equipment if equipment else '')
    return label[:1].upper()+label[1:]

def classify(row):
    n=row['name'].lower()
    if re.search(r'clean|snatch|jerk|overhead squat',n): return 'weightlifting'
    if row['body_part']=='cardio' or re.search(r'burpee|thruster|battling ropes|tire flip|kettlebell swing',n): return 'conditioning'
    if re.search(r'pull.up|chin.up|muscle.up|handstand|planche|lever$|ring dip|rope climb',n): return 'gymnastics'
    if re.search(r'deadlift|squat|bench press|shoulder press|military press|lunge',n): return 'strength'
    return 'accessory'

