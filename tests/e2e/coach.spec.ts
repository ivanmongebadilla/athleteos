import { expect, test } from "@playwright/test";
test.beforeEach(async ({ context, request }) => {
  await request.post("http://127.0.0.1:54329/reset");
  const encode = (value: unknown) => Buffer.from(JSON.stringify(value)).toString("base64url");
  const token = `${encode({ alg: "HS256", typ: "JWT" })}.${encode({ sub: "00000000-0000-4000-8000-000000000021", aud: "authenticated", role: "authenticated", exp: 2208988800, iat: 1735689600 })}.${Buffer.alloc(32).toString("base64url")}`;
  await context.addCookies([{ name: "sb-127-auth-token", value: `base64-${encode({ access_token: token, refresh_token: "local-fixture", token_type: "bearer", expires_in: 3600, expires_at: 2208988800 })}`, domain: "127.0.0.1", path: "/" }]);
});
test("coach welcome, personalization, persistence and Spanish editing", async ({ page }, info) => {
  await page.goto("/coach");
  await expect(page.getByRole("heading", { name: "Built around you." })).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("coach-welcome.png"), fullPage: true });
  await page.getByRole("button", { name: "Set up my coach", exact: true }).click();
  await expect(page.getByText("5 days / week · 60 min / session", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("radio", { name: /Olympic weightlifting/ }).check();
  await page.getByLabel("A goal you’re working toward").fill("Improve snatch consistency");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("radio", { name: /Explain the details/ }).check();
  await page.getByRole("button", { name: "Save coach preferences", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your next chapter starts here." })).toBeVisible();
  await expect(page.getByText("Improve snatch consistency", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Your next chapter starts here." })).toBeVisible();
  await page.getByRole("combobox", { name: "Language", exact: true }).selectOption("es");
  await expect(page.getByRole("heading", { name: "Tu próxima etapa empieza aquí." })).toBeVisible();
  await page.screenshot({ path: info.outputPath("coach-ready-es.png"), fullPage: true });
  await page.getByRole("button", { name: "Editar preferencias", exact: true }).click();
  await page.getByRole("button", { name: "Continuar", exact: true }).click();
  await expect(page.getByRole("radio", { name: /Halterofilia/ })).toBeChecked();
  await expect(page.getByLabel("Una meta que quieras alcanzar")).toHaveValue("Improve snatch consistency");
  await page.screenshot({ path: info.outputPath("coach-focus-es.png"), fullPage: true });
  await page.getByRole("button", { name: "Atrás", exact: true }).click();
  await page.getByRole("button", { name: "Cancelar", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Tu próxima etapa empieza aquí." })).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole("button", { name: /theme|tema/i }).click();
  await page.screenshot({ path: info.outputPath("coach-ready-dark.png"), fullPage: true });
});
